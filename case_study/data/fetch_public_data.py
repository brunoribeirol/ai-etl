"""Fetch the public datasets used by the case study and pin them in a manifest.

Replaces the script-generated `sales.csv`/`orders.csv` (see `generate_sales.py`,
`generate_orders.py`) for the evaluation runs: a reviewer can object that data
generated by the author, with the nulls and outliers injected on purpose, is
biased toward what the pipeline was built to detect. These sources are public,
citable, and their quality problems are the ones that occur in the published data.

Sources
-------
- NYC TLC Yellow Taxi Trip Records (one month, Parquet), published by the New
  York City Taxi and Limousine Commission:
  https://www.nyc.gov/site/tlc/about/tlc-trip-record-data.page
- NYC TLC Taxi Zone Lookup Table (CSV), same publisher.

The Open-Meteo archive API used by scenario 3 is called at run time by the REST
source, so nothing is fetched for it here.

What this script does NOT do
----------------------------
It never cleans, repairs or injects anything. The only transformations applied
to the trip records are a pickup-date window and a seeded row sample, both
recorded in the manifest, so the extract is reproducible from the raw file.

Outputs (all git-ignored except the manifest)
---------------------------------------------
- `case_study/data/yellow_tripdata_<month>.parquet`: raw download, untouched
- `case_study/data/nyc_taxi_trips.csv`: the windowed, sampled extract
- `case_study/data/taxi_zones.csv`: raw lookup table, untouched
- `case_study/public_data_manifest.json`: URLs, hashes, row counts

Usage
-----
    uv run python case_study/data/fetch_public_data.py            # fetch and write manifest
    uv run python case_study/data/fetch_public_data.py --verify   # compare against the manifest
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import httpx
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = REPO_ROOT / "case_study" / "data"
MANIFEST_PATH = REPO_ROOT / "case_study" / "public_data_manifest.json"

TLC_BASE_URL = "https://d37ci6vzurychx.cloudfront.net"
TLC_SOURCE_PAGE = "https://www.nyc.gov/site/tlc/about/tlc-trip-record-data.page"

DEFAULT_MONTH = "2025-01"
DEFAULT_WINDOW_START = "2025-01-06"
DEFAULT_WINDOW_END = "2025-01-12"  # inclusive: one full Monday-to-Sunday week
DEFAULT_SAMPLE_ROWS = 20_000
DEFAULT_SEED = 42

PICKUP_COLUMN = "tpep_pickup_datetime"
TRIPS_CSV = DATA_DIR / "nyc_taxi_trips.csv"
ZONES_CSV = DATA_DIR / "taxi_zones.csv"


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download(url: str, destination: Path) -> None:
    """Stream `url` to `destination`, replacing any previous copy."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    partial = destination.with_suffix(destination.suffix + ".part")
    with httpx.stream("GET", url, follow_redirects=True, timeout=120.0) as response:
        response.raise_for_status()
        with partial.open("wb") as handle:
            for chunk in response.iter_bytes(chunk_size=1 << 20):
                handle.write(chunk)
    partial.replace(destination)


def select_trips(
    trips: pd.DataFrame,
    window_start: str,
    window_end: str,
    sample_rows: int,
    seed: int,
) -> pd.DataFrame:
    """Return the reproducible extract: rows picked up inside the inclusive date
    window, then a seeded sample of at most `sample_rows`, in pickup order.

    No value is altered. Rows with a null or out-of-window pickup timestamp are
    excluded by the window itself; every other column is passed through as
    published, including its nulls, negatives and outliers.
    """
    start = pd.Timestamp(window_start)
    end_exclusive = pd.Timestamp(window_end) + pd.offsets.Day(1)
    pickup = trips[PICKUP_COLUMN]
    in_window = trips[(pickup >= start) & (pickup < end_exclusive)]
    if len(in_window) > sample_rows:
        in_window = in_window.sample(n=sample_rows, random_state=seed)
    return in_window.sort_values([PICKUP_COLUMN, "tpep_dropoff_datetime"], kind="stable")


def describe_quality(trips: pd.DataFrame) -> dict[str, Any]:
    """Counts of the quality problems present in the extract as published, recorded
    so the report can state what the data contained before the pipeline ran."""
    return {
        "rows": int(len(trips)),
        "exact_duplicate_rows": int(trips.duplicated().sum()),
        "null_counts": {
            column: int(count) for column, count in trips.isna().sum().items() if count > 0
        },
        "fare_amount_le_zero": int((trips["fare_amount"] <= 0).sum()),
        "trip_distance_le_zero": int((trips["trip_distance"] <= 0).sum()),
        "passenger_count_zero": int((trips["passenger_count"] == 0).sum()),
    }


def build_manifest(args: argparse.Namespace, raw_parquet: Path, trips: pd.DataFrame) -> dict:
    trips_url = f"{TLC_BASE_URL}/trip-data/{raw_parquet.name}"
    zones_url = f"{TLC_BASE_URL}/misc/taxi_zone_lookup.csv"
    return {
        "fetched_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "publisher": "New York City Taxi and Limousine Commission (TLC)",
        "source_page": TLC_SOURCE_PAGE,
        "trips": {
            "url": trips_url,
            "raw_file": raw_parquet.name,
            "raw_sha256": sha256_of(raw_parquet),
            "extract_file": TRIPS_CSV.name,
            "extract_sha256": sha256_of(TRIPS_CSV),
            "selection": {
                "pickup_window_start": args.window_start,
                "pickup_window_end_inclusive": args.window_end,
                "sample_rows": args.sample_rows,
                "seed": args.seed,
            },
            "columns": list(trips.columns),
            "quality_as_published": describe_quality(trips),
        },
        "zones": {
            "url": zones_url,
            "file": ZONES_CSV.name,
            "sha256": sha256_of(ZONES_CSV),
            "rows": int(len(pd.read_csv(ZONES_CSV))),
        },
        "weather": {
            "provider": "Open-Meteo Historical Weather API",
            "url": (
                "https://archive-api.open-meteo.com/v1/archive?latitude=40.71&longitude=-74.01"
                f"&start_date={args.window_start}&end_date={args.window_end}"
                "&daily=temperature_2m_max,precipitation_sum&timezone=America/New_York"
            ),
            "note": "Called at run time by the REST source in scenario 3; not stored here.",
        },
    }


def verify_against(manifest: dict) -> list[str]:
    """Return a list of mismatches between the files on disk and `manifest`."""
    problems = []
    checks = [
        (DATA_DIR / manifest["trips"]["raw_file"], manifest["trips"]["raw_sha256"]),
        (TRIPS_CSV, manifest["trips"]["extract_sha256"]),
        (ZONES_CSV, manifest["zones"]["sha256"]),
    ]
    for path, expected in checks:
        if not path.exists():
            problems.append(f"{path.name}: missing")
        elif sha256_of(path) != expected:
            problems.append(f"{path.name}: sha256 differs from the manifest")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--month", default=DEFAULT_MONTH, help="Trip-record month, YYYY-MM")
    parser.add_argument("--window-start", default=DEFAULT_WINDOW_START)
    parser.add_argument("--window-end", default=DEFAULT_WINDOW_END, help="Inclusive")
    parser.add_argument("--sample-rows", type=int, default=DEFAULT_SAMPLE_ROWS)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Fetch, then compare the result against the committed manifest instead of rewriting it",
    )
    args = parser.parse_args()

    raw_parquet = DATA_DIR / f"yellow_tripdata_{args.month}.parquet"
    if not raw_parquet.exists():
        print(f"Downloading {raw_parquet.name} ...")
        download(f"{TLC_BASE_URL}/trip-data/{raw_parquet.name}", raw_parquet)
    print("Downloading taxi_zone_lookup.csv ...")
    download(f"{TLC_BASE_URL}/misc/taxi_zone_lookup.csv", ZONES_CSV)

    trips = select_trips(
        pd.read_parquet(raw_parquet),
        args.window_start,
        args.window_end,
        args.sample_rows,
        args.seed,
    )
    trips.to_csv(TRIPS_CSV, index=False)
    print(f"Wrote {TRIPS_CSV.relative_to(REPO_ROOT)} ({len(trips)} rows)")

    if args.verify:
        if not MANIFEST_PATH.exists():
            print("No manifest to verify against.", file=sys.stderr)
            return 1
        problems = verify_against(json.loads(MANIFEST_PATH.read_text()))
        for problem in problems:
            print(f"MISMATCH: {problem}", file=sys.stderr)
        print("Manifest check: " + ("FAILED" if problems else "ok"))
        return 1 if problems else 0

    manifest = build_manifest(args, raw_parquet, trips)
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"Wrote {MANIFEST_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
